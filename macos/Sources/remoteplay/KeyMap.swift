// macOS 虛擬鍵碼 (kVK_*) → PC set-1 掃描碼 (+ 是否為 E0 延伸鍵)。
// 主機端用 KEYEVENTF_SCANCODE 注入，所以必須送「PC 掃描碼」而非 mac 鍵碼，否則會打錯鍵。
import CoreGraphics

enum KeyMap {
    // vk : (scancode, extended)
    static let table: [UInt16: (UInt16, Bool)] = [
        // 字母
        0x00: (0x1E, false), 0x0B: (0x30, false), 0x08: (0x2E, false), 0x02: (0x20, false),
        0x0E: (0x12, false), 0x03: (0x21, false), 0x05: (0x22, false), 0x04: (0x23, false),
        0x22: (0x17, false), 0x26: (0x24, false), 0x28: (0x25, false), 0x25: (0x26, false),
        0x2E: (0x32, false), 0x2D: (0x31, false), 0x1F: (0x18, false), 0x23: (0x19, false),
        0x0C: (0x10, false), 0x0F: (0x13, false), 0x01: (0x1F, false), 0x11: (0x14, false),
        0x20: (0x16, false), 0x09: (0x2F, false), 0x0D: (0x11, false), 0x07: (0x2D, false),
        0x10: (0x15, false), 0x06: (0x2C, false),
        // 數字列
        0x12: (0x02, false), 0x13: (0x03, false), 0x14: (0x04, false), 0x15: (0x05, false),
        0x17: (0x06, false), 0x16: (0x07, false), 0x1A: (0x08, false), 0x1C: (0x09, false),
        0x19: (0x0A, false), 0x1D: (0x0B, false),
        // 符號
        0x1B: (0x0C, false), 0x18: (0x0D, false), 0x21: (0x1A, false), 0x1E: (0x1B, false),
        0x2A: (0x2B, false), 0x29: (0x27, false), 0x27: (0x28, false), 0x32: (0x29, false),
        0x2B: (0x33, false), 0x2F: (0x34, false), 0x2C: (0x35, false),
        // 控制鍵
        0x24: (0x1C, false), // Return
        0x30: (0x0F, false), // Tab
        0x31: (0x39, false), // Space
        0x33: (0x0E, false), // Delete(Backspace)
        0x35: (0x01, false), // Escape
        // 修飾鍵（左）
        0x38: (0x2A, false), // Left Shift
        0x3B: (0x1D, false), // Left Control
        0x3A: (0x38, false), // Left Option(Alt)
        0x37: (0x5B, true),  // Left Command(Win)
        0x39: (0x3A, false), // CapsLock
        // 修飾鍵（右）
        0x3C: (0x36, false), // Right Shift
        0x3E: (0x1D, true),  // Right Control
        0x3D: (0x38, true),  // Right Option(AltGr)
        0x36: (0x5C, true),  // Right Command(Win)
        // 方向鍵（延伸）
        0x7E: (0x48, true), 0x7D: (0x50, true), 0x7B: (0x4B, true), 0x7C: (0x4D, true),
        // 導覽群組（延伸）
        0x73: (0x47, true), 0x77: (0x4F, true), 0x74: (0x49, true), 0x79: (0x51, true),
        0x72: (0x52, true), 0x75: (0x53, true),
        // 功能鍵
        0x7A: (0x3B, false), 0x78: (0x3C, false), 0x63: (0x3D, false), 0x76: (0x3E, false),
        0x60: (0x3F, false), 0x61: (0x40, false), 0x62: (0x41, false), 0x64: (0x42, false),
        0x65: (0x43, false), 0x6D: (0x44, false), 0x67: (0x57, false), 0x6F: (0x58, false),
        // 數字鍵盤
        0x52: (0x52, false), 0x53: (0x4F, false), 0x54: (0x50, false), 0x55: (0x51, false),
        0x56: (0x4B, false), 0x57: (0x4C, false), 0x58: (0x4D, false), 0x59: (0x47, false),
        0x5B: (0x48, false), 0x5C: (0x49, false), 0x41: (0x53, false), 0x45: (0x4E, false),
        0x4E: (0x4A, false), 0x43: (0x37, false), 0x4B: (0x35, true), 0x4C: (0x1C, true),
        0x47: (0x45, false), // Clear → NumLock
    ]

    static func scancode(for vk: UInt16) -> (UInt16, Bool)? { table[vk] }

    // flagsChanged 沒有明確的 down/up，用目前旗標是否含對應遮罩來判斷（左右共用遮罩為已知限制）
    static func modifierIsDown(vk: UInt16, flags: CGEventFlags) -> Bool {
        switch vk {
        case 0x38, 0x3C: return flags.contains(.maskShift)
        case 0x3B, 0x3E: return flags.contains(.maskControl)
        case 0x3A, 0x3D: return flags.contains(.maskAlternate)
        case 0x37, 0x36: return flags.contains(.maskCommand)
        case 0x39:       return flags.contains(.maskAlphaShift)
        default:         return false
        }
    }
}
